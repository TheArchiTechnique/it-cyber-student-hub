  assert.equal(shell.prompt(), 'student@student-linux:~$');
  assert.equal(ok('whoami').stdout, 'student\n');
  ok('mkdir -p ~/Practice/Reports'); ok('cd ~/Practice/Reports');
  assert.equal(ok('pwd').stdout, '/home/student/Practice/Reports\n');
  ok('echo "Linux workstation report" > report.txt');
  assert.match(ok('ls -la').stdout, /-rw-r--r-- 1 student student\s+25 .*report.txt/);
  assert.equal(ok('cat report.txt').stdout, 'Linux workstation report\n');
  ok('echo -n "Status: " >> report.txt'); ok('echo ready >> report.txt');
  assert.equal(ok('cat report.txt').stdout, 'Linux workstation report\nStatus: ready\n');
  ok('touch report.txt');
  assert.equal(ok('cat report.txt').stdout, 'Linux workstation report\nStatus: ready\n');
