// Stateful command sequences: no host command execution is involved in the engine.
const assert = require('node:assert/strict');
(async () => {
  const {Shell, complete} = await import('../docs/assets/javascripts/linux-terminal/shell.mjs');
  const {freshState, StateStore, STORAGE_KEY, restoreState} = await import('../docs/assets/javascripts/linux-terminal/state.mjs');
  const {parse} = await import('../docs/assets/javascripts/linux-terminal/parser.mjs');
  const {commandNames} = await import('../docs/assets/javascripts/linux-terminal/manuals.mjs');
  const shell = new Shell(freshState());
  const ok = line => { const result = shell.execute(line); assert.equal(result.code, 0, `${line}: ${result.stderr}`); return result; };
  const bad = (line, pattern) => { const result = shell.execute(line); assert.notEqual(result.code, 0, line); assert.match(result.stderr, pattern, line); return result; };
  assert.equal(shell.prompt(), 'student@student-linux:~$');
  assert.equal(ok('whoami').stdout, 'student\n');
  ok('mkdir -p ~/Practice/Reports'); ok('cd ~/Practice/Reports');
  assert.equal(ok('pwd').stdout, '/home/student/Practice/Reports\n');
  ok('echo "Linux workstation report" > report.txt');
  assert.match(ok('ls -la').stdout, /-rw-r--r-- 1 student student\s+25 .*report.txt/);
  assert.equal(ok('cat report.txt').stdout, 'Linux workstation report\n');
  ok('echo -n "Status: " >> report.txt'); ok('echo ready >> report.txt');
  assert.equal(ok('cat report.txt').stdout, 'Linux workstation report\nStatus: ready\n');
  ok('touch report.txt');
  assert.equal(ok('cat report.txt').stdout, 'Linux workstation report\nStatus: ready\n');
  ok('echo \"123\">number.txt'); assert.equal(ok('cat number.txt').stdout, '123\n');
  ok('echo replacement>report.txt'); assert.equal(ok('cat report.txt').stdout, 'replacement\n');
  ok('mkdir "Folder With Spaces"'); ok('cd "Folder With Spaces"');
  ok("echo '$HOME' > 'literal name.txt'");
  assert.equal(ok('cat "literal name.txt"').stdout, '$HOME\n');
  ok('echo "$PWD" > here.txt'); assert.equal(ok('cat here.txt').stdout, shell.state.cwd + '\n');
  ok('cd ..'); ok('cd -'); assert.match(shell.prompt(), /Folder With Spaces\$/);
  ok('cd'); assert.equal(shell.state.cwd, '/home/student');
  ok('touch Report.txt report.txt .hidden');
  assert.notEqual(shell.state.nodes['/home/student/Report.txt'], shell.state.nodes['/home/student/report.txt']);
  assert.ok(!ok('ls').stdout.includes('.hidden')); assert.match(ok('ls -a').stdout, /\.hidden/);
  assert.match(ok('ls -ld /etc').stdout, /^drwxr-xr-x .* \/etc\n$/);
  assert.equal(ok('ls -1 Documents').stdout, 'ticket.txt\n');
  ok('touch -- -notes'); assert.equal(ok('cat -- -notes').stdout, '');
  ok('mkdir -p Parent/Missing/Child/'); ok('cd Parent/Missing/Child/../.');
  assert.equal(shell.state.cwd, '/home/student/Parent/Missing');
  ok('cd ///'); ok('cd ../../..'); assert.equal(shell.state.cwd, '/');
  ok('cd "$HOME"'); bad('cd documents', /No such file/);
  bad('cd Documents/ticket.txt', /Not a directory/);
  bad('cat -', /interactive stdin/); bad('echo $$', /not supported/);
  bad('cat Documents', /Is a directory/); bad('cat absent', /No such file/);
  bad('cat /etc/shadow', /Permission denied/);
  bad('echo broken > /etc/hosts', /Permission denied/);
  bad('echo broken > /etc/new.conf', /Permission denied/);
  bad('mkdir /etc/new', /Permission denied/);
  bad('touch /etc/hosts', /Permission denied/);
  bad('cat /root/../etc/passwd', /Permission denied/);
  bad('echo broken > missing/child', /No such file/);
  bad('echo broken > Documents', /Is a directory/);
  bad('mkdir Documents', /File exists/);
  ok('mkdir -p Documents'); bad('mkdir', /missing operand/); bad('touch', /missing file/);
  bad('ls -R', /not supported/); bad('pwd bogus', /not supported/); bad('cat -n welcome.txt', /not supported/);
  bad('cd / /tmp', /too many/); bad('echo one | cat', /not supported/); bad('echo one; pwd', /not supported/);
  bad('echo $(whoami)', /not supported/); bad('echo `whoami`', /not supported/);
  bad('echo *.txt', /not supported/); bad('echo unclosed"', /unmatched quote/);
  bad('echo x >', /needs a filename/); bad('echo x > a > b', /multiple redirections/);
  bad('echo x 2> err.txt', /not supported/); bad('echo one\npwd', /multiple command/);
  bad('nano report.txt', /not yet supported/); bad('constructor', /command not found/);
  assert.equal(bad('nonexistent', /command not found/).code, 127);
  assert.equal(ok('echo $?').stdout, '127\n');
  ok('echo "<script>globalThis.bad=true</script>" > text.txt');
  assert.equal(globalThis.bad, undefined); assert.match(ok('cat text.txt').stdout, /<script>/);
  ok('echo before > new.txt'); bad('cat absent > new.txt', /No such file/); assert.equal(ok('cat new.txt').stdout, '');
  bad('cat text.txt > text.txt', /input file is output/); assert.equal(ok('cat text.txt').stdout, '');
  bad('cat absent welcome.txt', /No such file/); assert.match(shell.execute('cat absent welcome.txt').stdout, /Welcome/);
  const before = shell.state.nodes['/etc/hosts'].content;
  bad('echo change >/etc/hosts', /Permission denied/); assert.equal(shell.state.nodes['/etc/hosts'].content, before);
  ok('mkdir -p Private/inner');
  shell.state.nodes['/home/student/Private'].mode = 0o600;
  bad('cd Private/inner', /Permission denied/); bad('ls Private', /Permission denied/);
  shell.state.nodes['/home/student/Private'].mode = 0o700;
  ok('cd Private/inner'); ok('cd /tmp'); ok('echo temporary > test.txt'); ok('cd');
  for (const name of commandNames) {
    const result = ok(`man ${name}`); assert.equal(result.action, 'manual');
    assert.match(result.stdout, /SYNTAX/); assert.match(result.stdout, /EXAMPLE/);
  }
  bad('man nano', /No manual entry/); assert.match(ok('help cd').stdout, /working directory/);
  assert.equal(ok('clear').action, 'clear'); assert.ok(shell.state.nodes['/home/student/welcome.txt']);
  ok('man ls > ls-manual.txt'); assert.match(ok('cat ls-manual.txt').stdout, /SYNTAX/);
  assert.equal(ok('ls --help').action, null); assert.match(ok('ls --help').stdout, /OPTIONS/);
  assert.deepEqual(parse('echo "a > b" \'$HOME\' \\~', shell.environment()).argv, ['echo', 'a > b', '$HOME', '~']);
  assert.deepEqual(parse('echo "" $UNKNOWN x # comment', shell.environment()).argv, ['echo', '', 'x']);
  assert.deepEqual(parse('echo "$HOME" ${USER}', shell.environment()).argv, ['echo', '/home/student', 'student']);
  assert.deepEqual(parse('echo a\\ b \\$HOME', shell.environment()).argv, ['echo', 'a b', '$HOME']);
  assert.deepEqual(parse('echo $PWD', {PWD: '/a b'}).argv, ['echo', '/a', 'b']);
  assert.equal(complete(shell, 'who').value, 'whoami ');
  assert.equal(complete(shell, 'cd Doc').value, 'cd Documents/');
  assert.equal(complete(shell, 'cat Documents/ti').value, 'cat Documents/ticket.txt ');
  assert.equal(complete(shell, 'cd "Doc').value, 'cd "Doc');
  assert.equal(complete(shell, 'cd Practice/Reports/Folder').value, 'cd Practice/Reports/Folder\\ With\\ Spaces/');

  const memory = new Map([['unrelated-progress', 'keep']]);
  const storage = {getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value)};
  const store = new StateStore(storage);
  ok('cd Practice/Reports'); ok('echo persisted > saved.txt'); store.save(shell.state);
  const restored = new Shell(store.load());
  assert.equal(restored.state.cwd, '/home/student/Practice/Reports');
  assert.equal(restored.execute('cat saved.txt').stdout, 'persisted\n');
  assert.ok(restored.state.history.includes('echo persisted > saved.txt'));
  assert.equal(restored.state.nodes['/etc/shadow'].mode, 0o640);
  const reset = store.reset(); assert.equal(reset.cwd, '/home/student');
  assert.ok(!reset.nodes['/home/student/Practice/Reports/saved.txt']); assert.deepEqual(reset.history, []);
  assert.equal(memory.get('unrelated-progress'), 'keep');
  for (const value of ['broken JSON', JSON.stringify({version: 999}), JSON.stringify({...freshState(), cwd: '/missing'})]) {
    memory.set(STORAGE_KEY, value); assert.equal(store.load().cwd, '/home/student'); assert.match(store.message, /could not be loaded/);
  }
  const corrupted = freshState(); corrupted.nodes['/orphan/no-parent'] = {...corrupted.nodes['/etc/hosts']};
  assert.throws(() => restoreState(corrupted), /Orphaned/);
  const locked = freshState(); locked.nodes['/etc/hosts'].mode = -1; assert.throws(() => restoreState(locked), /Invalid/);
  const blocked = new StateStore({getItem() {throw Error('disabled');}, setItem() {throw Error('quota');}});
  assert.equal(blocked.load().cwd, '/home/student'); assert.equal(blocked.save(shell.state), false);
  assert.match(blocked.message, /unavailable or full/); assert.equal(blocked.reset().cwd, '/home/student');
  const deep = new Shell(freshState());
  const component = 'd'.repeat(240);
  while (deep.state.cwd.length + component.length + 1 < 8192) {
    assert.equal(deep.execute(`mkdir ${component}`).code, 0);
    assert.equal(deep.execute(`cd ${component}`).code, 0);
  }
  assert.match(deep.execute(`mkdir ${component}`).stderr, /File name too long/);
  assert.equal(restoreState(JSON.parse(JSON.stringify(deep.state))).cwd, deep.state.cwd);
  const large = new Shell(freshState());
  const originalSaved = memory.get(STORAGE_KEY);
  for (let i = 0; i < 9; i++) large.fs.write(`/tmp/large-${i}`, 'x'.repeat(900000));
  assert.equal(store.save(large.state), false);
  assert.equal(memory.get(STORAGE_KEY), originalSaved, 'Oversized saves preserve the previous checkpoint');
  for (let i = 0; i < 205; i++) ok('pwd'); assert.equal(shell.state.history.length, 200);
  assert.deepEqual(restoreState(JSON.parse(JSON.stringify(shell.state))).nodes, shell.state.nodes);
  console.log('PASS: shared filesystem command sequences, parser, quoting/expansion, redirection, permissions, errors, help/manuals, completion, persistence validation, isolation, reset, and bounded history.');
})().catch(error => {console.error(error); process.exitCode = 1;});
