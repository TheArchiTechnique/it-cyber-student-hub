  assert.equal(run.completed.length, 11);
  run.completed = []; check('handoff'); assert.equal(run.completed.length, 11);
  // Corrupting a real detached copy invalidates storage even with historical evidence.
  const earlierBackup = state.nodes[p.backup].content;
  state.nodes[p.backup].content = 'A changed archived report of sufficient length'; missing('archive'); state.nodes[p.backup].content = earlierBackup;
  const storedCopy = state.volumes[1].nodes[p.volume].content;
  state.volumes[1].nodes[p.volume].content = 'A different report of sufficient length'; missing('storage');
  state.volumes[1].nodes[p.volume].content = storedCopy;
