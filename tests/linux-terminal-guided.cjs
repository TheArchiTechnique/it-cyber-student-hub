  editor.save(); missing('nano'); editor.update(initial + 'Another observation in the same buffer.\n'); editor.save(); editor.close();
  command('cat workstation-report.txt'); missing('nano');
  editor = command('nano workstation-report.txt').editor;
  editor.update(initial + 'Support ticket 1042 is in progress.\n'); editor.save(); editor.close();
  command('ls'); command(`cat ${p.report}`); check('nano');
  command(`cp ${p.report} ${p.working}/report-copy.txt`);
  command(`mv ${p.working}/report-copy.txt ${p.backup}`);
  missing('archive'); command(`rm ${p.disposable}`); check('archive');
  command(`find ${p.workspace} -name "*.txt"`);
  command('grep -in error /var/log/application.log'); command(`grep student ${p.report}`);
  const add = text => command(`echo "${text}" >> ${p.report}`);
  add('Log findings: ERROR records missing configuration and an unavailable directory; INFO just records routine startup.'); check('search');
  command(`ls -l ${p.report}`); command(`chmod go-rwx,u+rw ${p.report}`);
  command(`echo "Safe permission exercise" > ${p.disposable}`);
  command(`chmod 200 ${p.disposable}`); command(`cat ${p.disposable}`, 1);
  assert.equal(run.evidence.deniedRead, true);
  command(`chmod u+r ${p.disposable}`);
  command(`sudo chown root:root ${p.disposable}`); missing('permissions');
  command(`sudo chown student:student ${p.disposable}`);
  command('sudo su -'); command('whoami'); missing('permissions'); command('exit');
  add('Permissions: 600 means only the owner can read and write the protected report.'); check('permissions');
  const permission = state.nodes[p.report].mode; state.nodes[p.report].mode = 0o640; missing('permissions'); state.nodes[p.report].mode = permission;
  command('ps aux'); command('top -b -n 1'); command(`du -hs ${p.reports}`); command('df -h');
  add('System: Bash PID 1042 belongs to student; NetworkManager is a service. CPU is mostly idle and memory has free space. du measures directory use; df measures filesystem capacity.'); check('resources');
  command('mount'); command('sudo mount /dev/sdb1 /mnt/training-disk'); command('cat /mnt/training-disk/README.txt');
  command(`cp ${p.report} /mnt/training-disk${p.volume}`);
  command('sudo fsck -n /dev/sdb1', 1); missing('storage');
  command('cd ~'); command('sudo umount /dev/sdb1'); command('sudo fsck -n /dev/sdb1');
  add('Storage: ext4 was mounted at /mnt/training-disk. The read-only check found consistent metadata and no errors.'); check('storage');
  command('apt list --installed'); command('apt search traceroute'); command('apt show traceroute');
  command('sudo apt remove traceroute'); command('traceroute portal.training.example', 127); missing('packages');
  command('apt install traceroute', 100); assert.equal(run.evidence.packageInstall, undefined);
  command('sudo apt install traceroute'); command('traceroute portal.training.example');
  add('Packages: traceroute traces network hops; sudo authorizes installation from a repository.'); check('packages');
  command('ip -br addr'); command('ip route show'); command('ping -c 2 192.0.2.1');
  command('dig portal.training.example +short'); command('traceroute portal.training.example'); command('curl -I http://files.training.example');
