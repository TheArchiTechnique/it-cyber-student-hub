  store.save(fedora); const mintAgain = store.switch('mint', fedora);
  assert.deepEqual(mintAgain.progress, state.progress); assert.equal(mintAgain.nodes[p.report].content, state.nodes[p.report].content);
  const count = Object.keys(state.nodes).length, next = newRun(state);
  assert.notEqual(next.workspace, p.workspace); assert.equal(Object.keys(state.nodes).length, count); assert.deepEqual(next.completed, []); assert.equal(state.nodes[p.report], savedReport);
