// Invoked by the existing browser harness against the built Pages subpath.
const assert = require('node:assert/strict');
module.exports = async function guidedBrowser({browser, base, route, origin}) {
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}}), errors = [], requests = [];
  await context.route('**/*', request => new URL(request.request().url()).origin === origin ? request.continue() : request.abort());
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  const input = page.locator('#command');
  const run = async command => {
    await input.fill(command); await input.press('Enter');
    await page.waitForFunction(() => document.getElementById('command').value === '');
  };
  const snapshot = () => page.evaluate(() => JSON.parse(localStorage.getItem('student-hub:linux-terminal:v1')));
  const stage = id => page.locator('#guided-stage').selectOption(id);
  const verify = async ok => {
    await page.locator('#check-guided').click();
    const text = await page.locator('#guided-feedback').textContent();
    assert.equal(text.includes('Stage verified'), ok, text);
  };
  const nano = async (filename, content) => {
    await run('nano ' + filename);
    await page.locator('#nano-buffer').fill(content);
    await page.locator('#nano-buffer').press('Control+o');
    await page.locator('#nano-write-name').press('Enter');
    await page.locator('#nano-buffer').press('Control+x');
  };
  const add = text => run(`echo "${text}" >> ${report}`);
  await page.goto(base + route); await input.waitFor();
  await run('echo "Existing student work" > ~/existing.txt');
  const before = await snapshot();
  await page.locator('#guided-mode').click();
  const workspace = await page.locator('#guided-workspace').textContent(), report = workspace + '/Reports/workstation-report.txt';
  const reports = workspace + '/Reports', working = workspace + '/Working', archive = workspace + '/Archive';
  assert.deepEqual((await snapshot()).nodes, before.nodes); // Starting instructions creates no solved files.
  await verify(false);
  for (const command of ['pwd', 'ls', 'cd /', 'ls', 'cd ~', 'whoami', 'cat ~/Documents/ticket.txt', 'man ls']) await run(command);
  await page.locator('#manual-content').waitFor(); await page.keyboard.press('q');
  await run('help'); await verify(true);
  await page.locator('#next-stage').click(); assert.equal(await page.locator('#guided-stage').inputValue(), 'workspace');
  await verify(false);
  await page.locator('#guided-hint-details > summary').click(); await page.locator('#guided-example-details > summary').click();
  assert.match(await page.locator('#guided-example').textContent(), /mkdir -p/);
  for (const command of [`mkdir -p ${working} ${reports} ${archive}`, `cd ${workspace}`, 'pwd', 'ls', `touch ${working}/disposable.txt`, `echo "Technician workspace prepared" > ${working}/setup-notes.txt`, `echo "Reports and archives are separate" >> ${working}/setup-notes.txt`, `cat ${working}/setup-notes.txt`]) await run(command);
  assert.equal(await page.locator('#guided-example-details').evaluate(node => node.open), true);
  await verify(true); await stage('nano'); await verify(false);
  await run(`cd ${reports}`); await run('nano workstation-report.txt');
  assert.equal(await page.locator('#check-guided').isDisabled(), true);
  assert.equal(await page.locator('#new-assignment').isDisabled(), true);
  assert.equal(await page.locator('#fedora-extension').isDisabled(), true);
  await page.locator('#nano-buffer').fill('Unsaved text is not a completed report');
  await page.locator('#nano-exit').click(); await page.locator('#nano-discard').click(); await verify(false);
  const initial = 'Workstation: student-linux operated by student\nWorkspace: Working, Reports, and Archive prepared for support.\nSupport ticket 1042 is in progress.';
  await nano('workstation-report.txt', initial); await verify(false);
  await run('cat workstation-report.txt');
  await nano('workstation-report.txt', initial + '\nSaved notes were reopened and revised.');
  await run('ls'); await run('cat workstation-report.txt'); await verify(true);
  const saved = await snapshot();
  await page.reload(); await input.waitFor();
  assert.equal(await page.locator('#guided-stage').inputValue(), 'nano');
  assert.match(await page.locator('#guided-progress-text').textContent(), /3 of 11/);
  assert.equal((await snapshot()).nodes[report].content, saved.nodes[report].content);
  await page.locator('#free-mode').click(); assert.equal(await page.locator('#guided-panel').isVisible(), false);
  await run('cat workstation-report.txt'); assert.match(await page.locator('#terminal-output').textContent(), /reopened and revised/);
  const free = await snapshot(); await page.locator('#guided-mode').click(); const guided = await snapshot();
  for (const key of ['nodes', 'cwd', 'user', 'packages', 'network', 'history']) assert.deepEqual(guided[key], free[key], key);
  await stage('archive'); await verify(false);
  for (const command of [`cp ${report} ${working}/copy.txt`, `mv ${working}/copy.txt ${archive}/workstation-report-backup.txt`, `rm ${working}/disposable.txt`]) await run(command);
  await verify(true); await stage('search'); await verify(false);
  for (const command of [`find ${workspace} -name "*.txt"`, 'grep -in error /var/log/application.log', 'cat /var/log/application.log', `grep student ${report}`]) await run(command);
  await add('Log findings: ERROR records missing configuration and an unavailable directory; INFO just records routine startup.'); await verify(true);
  await stage('permissions'); await verify(false);
  for (const command of [`ls -l ${report}`, `chmod 600 ${report}`, `echo "Disposable permission test" > ${working}/disposable.txt`, `chmod 200 ${working}/disposable.txt`, `cat ${working}/disposable.txt`, `chmod u+r ${working}/disposable.txt`, `sudo chown root:root ${working}/disposable.txt`, `sudo chown student:student ${working}/disposable.txt`, 'sudo su -', 'whoami', 'exit']) await run(command);
  await add('Permissions: mode 600 allows only the owner to read and write the protected report.'); await verify(true);
  await stage('resources'); await verify(false);
  await run('ps -ef'); await run('top'); await page.keyboard.press('q');
  await run(`du -sh ${reports}`); await run('df -h');
  await add('System: Bash PID 1042 belongs to student; NetworkManager is a service. CPU is mostly idle and memory is available. du measures directory usage; df measures filesystem capacity.'); await verify(true);
  await stage('storage'); await verify(false);
  for (const command of ['mount', 'sudo mount /dev/sdb1 /mnt/training-disk', 'ls /mnt/training-disk', 'cat /mnt/training-disk/README.txt', `cp ${report} /mnt/training-disk/Reports/${workspace.split('/').at(-1)}-report.txt`, 'cd ~', 'sudo umount /dev/sdb1', 'sudo fsck -n /dev/sdb1']) await run(command);
  await add('Storage: ext4 was mounted at /mnt/training-disk; the read-only check found consistent metadata and no errors.'); await verify(true);
  await stage('packages'); await verify(false);
  for (const command of ['apt list --installed', 'apt search traceroute', 'apt show traceroute', 'sudo apt remove traceroute', 'traceroute portal.training.example', 'sudo apt install traceroute', 'apt list --installed', 'traceroute portal.training.example']) await run(command);
  await add('Packages: traceroute investigates network hops; sudo authorizes package installation from the repository.'); await verify(true);
  await stage('network'); await verify(false);
  for (const command of ['ip addr', 'ip route', 'ping -c 2 192.0.2.1', 'dig portal.training.example', 'traceroute portal.training.example', 'curl -I http://files.training.example', `curl -o ${working}/service-report.html http://files.training.example/report`, `cat ${working}/service-report.html`, 'dig missing.training.example', 'dig unavailable.training.example', 'ping -c 2 unavailable.training.example', 'curl -I http://status.training.example']) await run(command);
  await add('Network: enp0s3 uses 192.0.2.10/24, gateway 192.0.2.1; portal DNS is 198.51.100.20. Missing record returns NXDOMAIN; unavailable destination is unreachable; HTTP 503 identifies a responding application service failure.'); await verify(true);
  await stage('handoff'); await verify(false);
  await add('Final status: Workstation preparation complete; escalate the remote service fault and investigate its application logs next.');
  await run(`cp ${report} ${archive}/workstation-report-final.txt`); await run(`chmod 600 ${archive}/workstation-report-final.txt`); await verify(true);
  assert.match(await page.locator('#guided-progress-text').textContent(), /11 of 11/);
  await run(`rm ${archive}/workstation-report-final.txt`); await verify(false);
  await run(`cp ${report} ${archive}/workstation-report-final.txt`); await verify(true);
  await page.locator('#previous-stage').click(); assert.equal(await page.locator('#guided-stage').inputValue(), 'network');
  await page.locator('#next-stage').click();
  // Both themes at desktop/mobile widths keep controls and editor in the document flow.
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({width, height: 1000});
    for (const theme of ['default', 'slate']) {
      if (await page.locator('body').getAttribute('data-md-color-scheme') !== theme) await page.locator('#theme-toggle').click();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${width}/${theme}`);
      const positions = await page.evaluate(() => ({panel: document.getElementById('guided-panel').getBoundingClientRect().toJSON(), terminal: document.querySelector('.linux-terminal').getBoundingClientRect().toJSON()}));
      if (width === 1440) assert.ok(positions.terminal.x > positions.panel.x + positions.panel.width);
      else assert.ok(positions.terminal.y >= positions.panel.y + positions.panel.height);
      if (process.env.LINUX_TERMINAL_QA_DIR) { await require('node:fs/promises').mkdir(process.env.LINUX_TERMINAL_QA_DIR, {recursive:true}); await page.screenshot({path:require('node:path').join(process.env.LINUX_TERMINAL_QA_DIR, `guided-${width}-${theme}.png`),fullPage:true}); }
    }
  }
  await page.setViewportSize({width:1440,height:1000});
  const mint = await snapshot();
  await page.locator('#fedora-extension').click();
  assert.equal(await page.locator('#workstation-profile').inputValue(), 'fedora');
  assert.equal(await page.locator('#guided-stage').inputValue(), 'fedora'); await verify(false);
  const fedoraWorkspace = await page.locator('#guided-workspace').textContent();
  for (const command of ['dnf list installed', 'man dnf']) await run(command);
  await page.keyboard.press('q');
  for (const command of ['dnf info support-notes', 'sudo dnf install support-notes', 'dnf info support-notes', `mkdir -p ${fedoraWorkspace}/Working`, `echo "Fedora uses DNF; support-notes installed" > ${fedoraWorkspace}/Working/dnf-notes.txt`]) await run(command);
  await verify(true); await page.reload(); await input.waitFor();
  assert.match(await page.locator('#guided-progress-text').textContent(), /1 of 1/);
  await page.locator('#workstation-profile').selectOption('mint');
  assert.deepEqual((await snapshot()).nodes, mint.nodes); assert.deepEqual((await snapshot()).progress, mint.progress);
  await page.locator('#new-assignment').click(); await page.locator('#cancel-assignment').click();
  assert.equal(await page.locator('#guided-workspace').textContent(), workspace);
  await page.locator('#new-assignment').click(); await page.locator('#confirm-assignment').click();
  assert.notEqual(await page.locator('#guided-workspace').textContent(), workspace);
  assert.deepEqual((await snapshot()).nodes, mint.nodes); assert.deepEqual((await snapshot()).packages, mint.packages);
  assert.match(await page.locator('#guided-progress-text').textContent(), /0 of 11/);
  await page.locator('#reset-workstation').click(); await page.locator('#cancel-reset').click();
  assert.equal((await snapshot()).nodes[report].content, mint.nodes[report].content);
  await page.locator('#reset-workstation').click(); await page.locator('#confirm-reset').click();
  assert.equal(await page.locator('#guided-panel').isVisible(), false); assert.equal((await snapshot()).nodes[report], undefined);
  await page.locator('#workstation-profile').selectOption('fedora'); assert.match(await page.locator('#guided-progress-text').textContent(), /1 of 1/);
  assert.deepEqual(errors, []);
  assert.ok(requests.every(url => new URL(url).origin === origin || url === 'https://cloud.umami.is/script.js'), 'Commands must not create real network traffic');
  await context.close();
  // Touch buttons perform Nano saves while guided instructions remain accessible.
  const touch = await browser.newContext({viewport: {width:390,height:844}, isMobile:true, hasTouch:true});
  const mobile = await touch.newPage(); await mobile.goto(base + route);
  await mobile.locator('#guided-mode').tap();
  const mw = await mobile.locator('#guided-workspace').textContent();
  const typed = async command => { await mobile.locator('#command').fill(command); await mobile.locator('#terminal-form button[type=submit]').tap(); };
  await typed(`mkdir -p ${mw}/Reports`); await mobile.locator('#guided-stage').selectOption('nano');
  await typed(`nano ${mw}/Reports/workstation-report.txt`);
  await mobile.locator('#nano-buffer').fill('Workstation: student-linux\nTechnician account: student\nReports workspace prepared.');
  await mobile.locator('#nano-write').tap(); await mobile.locator('#nano-write-form button[type=submit]').tap(); await mobile.locator('#nano-exit').tap();
  assert.equal(await mobile.locator('#check-guided').isDisabled(), false);
  await mobile.locator('#check-guided').tap(); assert.match(await mobile.locator('#guided-feedback').textContent(), /reopen/);
  await mobile.locator('#free-mode').tap(); await typed(`cat ${mw}/Reports/workstation-report.txt`);
  assert.match(await mobile.locator('#terminal-output').textContent(), /Reports workspace prepared/);
  await mobile.locator('#guided-mode').tap(); assert.equal(await mobile.locator('#guided-stage').inputValue(), 'nano');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await touch.close();
  console.log('PASS: Guided browser student walkthrough across all 12 stages, partial-work feedback, keyboard/touch Nano, shared Free Practice state, refresh/stage navigation, desktop/mobile themes, new-run preservation, and independent Fedora/reset.');
};
